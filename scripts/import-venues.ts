/**
 * 전국 예식장 CSV → Supabase venues 테이블 import
 *
 *   npm run import:venues:dry          # DB에 쓰지 않고 변환 결과만 확인
 *   npm run import:venues              # .env.local 의 키로 실제 upsert
 *   npm run import:venues -- data/다른파일.csv
 *   npm run import:venues:dry -- --sql=supabase/seed.sql
 *                                      # 키 없이 SQL 파일로 내보내기 → Supabase SQL Editor에 붙여넣어 실행
 *
 * - 여러 번 돌려도 안전 (source_key 기준 upsert).
 * - 원본(CSV) 컬럼만 덮어쓰고, 사용자가 입력한 주차·촬영 정보는 건드리지 않음.
 * - RLS를 우회해야 하므로 SUPABASE_SERVICE_ROLE_KEY 가 필요 (이 스크립트에서만 사용, 프론트에 노출 금지).
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "csv-parse/sync";
import { createClient } from "@supabase/supabase-js";

const DEFAULT_CSV = "data/전국_예식장_목록_호텔포함.csv";
const BATCH_SIZE = 200;

type CsvRow = Record<
  | "시도" | "시군구" | "상호명" | "지점명" | "도로명주소" | "지번주소" | "건물명" | "층"
  | "위도" | "경도" | "구분" | "예식확인" | "호텔등급" | "객실수" | "전화번호" | "홈페이지"
  | "등록업종" | "상가업소번호" | "같은주소_업소수" | "통합전_상호",
  string
>;

type VenueCategory = "wedding_hall" | "hotel_4" | "hotel_5" | "auxiliary";

const blank = (v: string | undefined) => {
  const t = (v ?? "").trim();
  return t === "" ? null : t;
};

function toCategory(raw: string): VenueCategory {
  const v = raw.trim();
  if (v === "예식장업") return "wedding_hall";
  if (v === "호텔(4성)") return "hotel_4";
  if (v === "호텔(5성)") return "hotel_5";
  if (v.startsWith("보조")) return "auxiliary";
  throw new Error(`알 수 없는 구분 값: "${raw}"`);
}

function toVenue(r: CsvRow, line: number) {
  const lat = Number(r.위도);
  const lng = Number(r.경도);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) {
    throw new Error(`${line}행: 위도/경도가 숫자가 아님 (${r.위도}, ${r.경도})`);
  }
  const bizNo = blank(r.상가업소번호);
  const roadAddress = blank(r.도로명주소);
  if (!roadAddress) throw new Error(`${line}행: 도로명주소 없음`);

  // 상가업소번호가 없는 호텔은 상호명+도로명주소 해시로 고정 키 생성
  const sourceKey =
    bizNo ??
    "h:" + createHash("sha1").update(`${r.상호명.trim()}|${roadAddress}`).digest("hex").slice(0, 16);

  const rooms = blank(r.객실수);

  return {
    source_key: sourceKey,
    biz_no: bizNo,
    sido: r.시도.trim(),
    sigungu: r.시군구.trim(),
    name: r.상호명.trim(),
    branch_name: blank(r.지점명),
    road_address: roadAddress,
    jibun_address: blank(r.지번주소),
    building_name: blank(r.건물명),
    floor: blank(r.층),
    lat,
    lng,
    category: toCategory(r.구분),
    wedding_confirm: blank(r.예식확인),
    hotel_grade: blank(r.호텔등급),
    room_count: rooms ? Math.round(Number(rooms)) : null,
    phone: blank(r.전화번호),
    homepage: blank(r.홈페이지),
    registered_industry: blank(r.등록업종),
    former_names: blank(r.통합전_상호),
  };
}

type Venue = ReturnType<typeof toVenue>;

/** source_key 기준 upsert SQL (원본 컬럼만 갱신, 사용자 입력 컬럼 보존) */
function toUpsertSql(venues: Venue[]) {
  const cols = Object.keys(venues[0]) as (keyof Venue)[];
  const lit = (v: unknown) =>
    v === null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
  const values = venues.map((v) => `  (${cols.map((c) => lit(v[c])).join(", ")})`).join(",\n");
  const updates = cols
    .filter((c) => c !== "source_key")
    .map((c) => `${c} = excluded.${c}`)
    .join(",\n  ");
  return (
    `-- ${venues.length} venues, generated by scripts/import-venues.ts\n` +
    `insert into public.venues (${cols.join(", ")}) values\n${values}\n` +
    `on conflict (source_key) do update set\n  ${updates};\n`
  );
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");
  const sqlOut = args.find((a) => a.startsWith("--sql="))?.slice("--sql=".length);
  const csvPath = args.find((a) => !a.startsWith("--")) ?? DEFAULT_CSV;

  // csv-parse 의 bom 옵션으로 UTF-8 BOM 제거
  const rows: CsvRow[] = parse(readFileSync(csvPath), {
    bom: true,
    columns: true,
    skip_empty_lines: true,
  });
  const venues = rows.map((r, i) => toVenue(r, i + 2));

  const dupKeys = venues
    .map((v) => v.source_key)
    .filter((k, i, arr) => arr.indexOf(k) !== i);
  if (dupKeys.length) throw new Error(`source_key 중복: ${dupKeys.join(", ")}`);

  const byCategory = venues.reduce<Record<string, number>>((acc, v) => {
    acc[v.category] = (acc[v.category] ?? 0) + 1;
    return acc;
  }, {});
  const addrCount = venues.reduce<Record<string, number>>((acc, v) => {
    acc[v.road_address] = (acc[v.road_address] ?? 0) + 1;
    return acc;
  }, {});
  const sharedAddresses = Object.values(addrCount).filter((n) => n > 1).length;

  console.log(`CSV: ${csvPath}`);
  console.log(`예식장 ${venues.length}곳`, byCategory);
  console.log(`상가업소번호 없음(해시 키): ${venues.filter((v) => !v.biz_no).length}곳`);
  console.log(`같은 도로명주소 그룹: ${sharedAddresses}개 (지도에서 마커 하나로 묶임)`);

  if (sqlOut) {
    writeFileSync(sqlOut, toUpsertSql(venues));
    console.log(`\nSQL 파일 저장: ${sqlOut}`);
    return;
  }

  if (dryRun) {
    console.log("\n--dry-run: DB에 쓰지 않음. 첫 행 예시:\n", venues[0]);
    return;
  }

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !serviceKey) {
    throw new Error(".env.local 에 NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY 를 넣어주세요.");
  }
  const supabase = createClient(url, serviceKey, { auth: { persistSession: false } });

  for (let i = 0; i < venues.length; i += BATCH_SIZE) {
    const batch = venues.slice(i, i + BATCH_SIZE);
    const { error } = await supabase.from("venues").upsert(batch, { onConflict: "source_key" });
    if (error) throw new Error(`upsert 실패 (${i + 1}~${i + batch.length}행): ${error.message}`);
    console.log(`  ${Math.min(i + BATCH_SIZE, venues.length)}/${venues.length}`);
  }

  const { count, error } = await supabase.from("venues").select("*", { count: "exact", head: true });
  if (error) throw error;
  console.log(`완료. venues 테이블 총 ${count}행`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
